//! Собственная группа процессов для встроенного режима.

/// Увести процесс в СОБСТВЕННУЮ группу, оставшись в той же сессии.
///
/// `setpgid(0, 0)`, а НЕ `setsid()`: сессия несёт управляющий терминал, и `setsid` отнял бы у
/// человека и `Ctrl+C`, и прогресс-бар. Группа даёт оркестратору ровно то, что он просил, —
/// `kill(-pgid)` снимает подборщик вместе со всеми детьми одним вызовом, не перебирая pid'ы и
/// не гадая, кто из них наш.
///
/// Зовётся ТОЛЬКО во встроенном режиме. В интерактивном `Ctrl+C` приходит всей группе
/// переднего плана — отделяться от неё значило бы отобрать у человека привычный обрыв, а
/// взамен дать обработчик, который и так уже есть.
///
/// Уже быть лидером группы — не отказ: `setpgid` в этом случае ничего не меняет и возвращает
/// успех. Отказ возможен на сессии-лидере (`EPERM`), и он не смертелен: без своей группы
/// оркестратору остаётся бить по pid, а детей снимет `PDEATHSIG`.
pub fn detach_into_own_group() -> std::io::Result<()> {
    // SAFETY: аргументы — нули («этот процесс», «новая группа с его номером»), и
    // вызов не трогает чужую память.
    match unsafe { libc::setpgid(0, 0) } {
        0 => Ok(()),
        _ => Err(std::io::Error::last_os_error()),
    }
}

/// Номер группы процессов, в которой мы сейчас. Оркестратору его называет отчёт: по нему он и
/// бьёт, когда подбор пора снимать.
pub fn own_group() -> i32 {
    // SAFETY: `getpgrp` не принимает аргументов и не может отказать.
    unsafe { libc::getpgrp() }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// После ухода в свою группу её номер обязан совпасть с нашим pid — иначе `kill(-pgid)`
    /// оркестратора пришёл бы не нам, а той группе, из которой мы не ушли.
    ///
    /// Тест НЕ возвращает прежнюю группу: обратного хода у `setpgid` нет (вернуться в чужую
    /// группу нельзя, если её лидер уже мёртв), и тестовый процесс живёт с новой группой до
    /// конца. Это безопасно — `cargo test` не шлёт сигналов по группе.
    #[test]
    fn entering_our_own_group_makes_us_its_leader() {
        // Отказ возможен только у лидера сессии; в тестовом бинаре мы им не являемся.
        detach_into_own_group().expect("уход в свою группу");
        assert_eq!(
            own_group(),
            std::process::id() as i32,
            "лидер группы обязан носить наш pid"
        );
    }
}
