#!/usr/bin/env bash
# Пик RAM и состояние очереди при подборе страт: старая схема (процесс на
# стратегию) против профилей в одном nfqws2 (#68, задача 10, ЧАСТЬ A). Запуск
# ВНУТРИ привилегированного контейнера-стенда — тем же способом, что
# nfq-throughput-ab.sh и scan-packet-rate.sh.
#
#   tests/repro/scan-rss-ab.sh [домен] [таймаут_с] [K]
#
#   домен      цель скана (по умолчанию rutracker.org)
#   таймаут_с  общий таймаут scan --timeout (по умолчанию 70)
#   K          --profiles-per-instance: сколько стратегий держать в одном
#              nfqws2 (по умолчанию 1024 — боевое значение). Игнорируется на
#              билде, где такого флага ещё нет (см. HAS_PPI ниже).
#
#   BIN        (переменная окружения, НЕ позиционный аргумент) — путь к
#               бинарю blockcheckw. По умолчанию /app/target/debug/blockcheckw
#               (текущий билд). Смысл A/B (см. §5 отчёта задачи 10А) — прогнать
#               ЭТОТ скрипт дважды на РАЗНЫХ билдах: старом (до задачи 8ч2,
#               без `--profiles-per-instance`) и новом. Пример:
#                 BIN=/oldsrc/target/debug/blockcheckw tests/repro/scan-rss-ab.sh
#                 tests/repro/scan-rss-ab.sh   # без BIN — берётся билд по умолчанию
#              Fix round 2: раньше `BIN` был захардкожен внутри скрипта, и
#              указать ему второй билд было нечем — A/B, ради которого скрипт
#              вообще писался, был физически невыполним. `setup-router.sh` и
#              лог-файлы ($log ниже) НЕ переопределяются вместе с `BIN`: это
#              фикстура и артефакты самого прогона, они принадлежат текущему
#              чекауту репозитория (`/app`), а не тому билду, что сейчас
#              меряется — старый билд из `/oldsrc` может вообще не содержать
#              копии `tests/repro/`, если собран из старого коммита в
#              отдельном дереве.
#
#   ВАЖНО (Fix round 2): после смены пина сабмодуля `reference/zapret2`
#   образ/контейнер-стенд ОБЯЗАН быть пересобран (`docker build`), а не
#   переиспользован как есть — `docker/integration.Dockerfile` собирает
#   `nfqws2` из `reference/zapret2/nfq2/` НА ЭТАПЕ СБОРКИ ОБРАЗА, а не при
#   старте контейнера. Если этого не сделать, движок внутри останется без
#   `--filter-mark`, и преflight в `$BIN` откажет с ненулевым кодом возврата
#   (не тихий ноль — C1 выше это теперь ловит громко, но лучше не тратить на
#   это прогон).
#
# Fix round 1 (ревью сильной модели): весь скрипт переписан — измерительная
# часть черновика была недостоверна на своих собственных допущениях. Что
# изменилось и почему — см. комментарии по месту и
# docs/research/68-nfqws2-parallelism.md /
# .../task-10a-report.md (раздел "Fix round 1").
#
# Fix round 2: `BIN` стал переопределяемым из окружения (см. выше) —
# без этого сравнить старую и новую схему было нечем в принципе; добавлена
# вторая честная граница метода счёта запусков по PID (ниже); напоминание
# про пересборку образа перенесено сюда же, в шапку скрипта (в отчёте оно
# было, но туда, где его увидит оператор, не попало).
#
# На каждом из трёх уровней параллелизма (--workers 8, 64, 1024) меряются:
#   - пик суммарного PSS по всем живым nfqws2 за прогон;
#   - число реальных запусков движка — по УНИКАЛЬНЫМ PID процессов nfqws2,
#     увиденным за время прогона (см. ниже, почему не по логу);
#   - число стратегий, реально обработанных до дедлайна (`completed:` из
#     `ui::stats_line`, НЕ размер сгенерированного корпуса);
#   - объём трафика, прошедшего через наши метки (отдельная наблюдательная
#     nft-цепочка со счётчиками — не зависит от перебиндов очереди);
#   - потери очереди (колонки 6+7 из /proc/net/netfilter/nfnetlink_queue) по
#     всему диапазону очередей 200..1300, а не только 200.
#
# ── Число запусков: почему по PID, а не по логу ──────────────────────────
#
# Черновик v1 считал по строке "nfqws2 instance started" (появляется только
# в новой схеме, `info!` в src/pipeline/runner.rs) с ручным фолбэком на
# "старая схема — запусков равно стратегиям". Это оказалось ХУЖЕ, чем просто
# неточно: "стратегии" сами по себе — это РАЗМЕР СГЕНЕРИРОВАННОГО КОРПУСА
# (см. про `tried` ниже), а не число реально опробованных, и на старой схеме
# при 8 воркерах с общим таймаутом реально запускается пара штук, а не весь
# корпус. Фолбэк "старт = стратегии" завышал бы старую схему на порядки и
# ломал сам смысл замера.
#
# Вместо этого: `pgrep -x nfqws2` на каждом тике 50-мс опроса (тот же цикл,
# что снимает PSS), уникальные PID собираются в множество, мощность
# множества — и есть `запусков`. Работает ОДИНАКОВО на обеих схемах, не
# зависит ни от строки в логе, ни от RUST_LOG, ни от того, какой билд вообще
# запущен.
#
# Честные границы метода — их две, не одна:
# 1. Процесс, проживший меньше 50 мс между двумя тиками, может быть пропущен
#    полностью.
# 2. Если ядро успело переиспользовать номер PID в пределах ОДНОГО уровня
#    параллелизма (короткий процесс завершился, а следующий получил тот же
#    PID до следующего тика) — два разных процесса схлопнутся в одну запись
#    множества `seen_pids`.
# Оба смещения — в ОДНУ сторону: недосчёт. Для старой схемы (короткие
# процессы, один на стратегию — то есть именно та схема, где оба эффекта
# наиболее вероятны) это ЗАНИЖЕНИЕ — метод консервативен в сторону
# преуменьшения эффекта #68, а не наоборот, так что вывод "новая схема
# радикально меньше" при таком смещении только усиливается, если он вообще
# виден.
#
# ── Число стратегий: не корпус, а обработанные ───────────────────────────
#
# `"{N} strategies, workers={W}"` (`src/cmd/scan.rs`) — это размер
# СГЕНЕРИРОВАННОГО корпуса на протокол (~4600 на протокол), печатается ДО
# запуска. При общем `--timeout` (дедлайн на весь скан, `tokio::time::timeout`
# вокруг `scan_future` в `src/cmd/scan.rs`) реально обрабатывается на порядки
# меньше, и асимметрично по схемам — использовать эту строку для "сколько
# опробовано" значило бы сравнивать сфабрикованные тысячи против честных
# единиц.
#
# Настоящее число процессов — `"  completed: {N} | success: ... "`
# (`ui::stats_line`, `src/ui.rs`), печатается ПОСЛЕ того, как протокол
# доработал (не при обрыве по дедлайну: `tokio::time::timeout` в scan.rs
# просто роняет future, и для протокола, обрываемого дедлайном, этой строки
# не будет вовсе). Берём сумму `completed` по всем найденным строкам и
# явно считаем, сколько из ожидаемых протоколов (по умолчанию 3:
# http,tls12,tls13) успели напечатать её — если меньше, "стратегий" это
# НИЖНЯЯ ГРАНИЦА, а не точное число, и это помечается в выводе.
#
# Раньше (v1) для этой же цели бралась строка `"- {test} ipv4 {domain} :
# nfqws2 ..."` (`src/pipeline/runner.rs`) — она РЕАЛЬНО существует (это не
# придуманный "^- http_test" из черновика), но идёт через
# `MultiProgress::println` НАПРЯМУЮ (`m.println(&line)`, `runner.rs`), а
# `Console::new()` (`src/ui.rs`) создаёт `MultiProgress` с
# `ProgressDrawTarget::hidden()`, когда стандартный поток — не терминал
# (`Term::stderr().is_term()`); печать на скрытый target — молчаливый no-op у
# indicatif. При перенаправлении в файл (наш случай, `>>"$log"`) эта строка
# никогда не попадает в лог. `ui::stats_line` печатается иначе — через
# `Console::println`, у которого явный фолбэк `else { eprintln!(...) }` на
# не-tty — поэтому и попадает в лог, а построчная — нет.
#
# ── Единственная очередь — только у новой схемы ──────────────────────────
#
# У новой схемы `--qnum` нет: очередь всегда `CoreConfig::base_qnum` = 200,
# без флага на смену (`grep base_qnum src/*.rs`). Но старая схема (снесённый
# `src/worker/slot.rs`, `git show HEAD:src/worker/slot.rs`) раздаёт
# `fwmark = WORKER_MARK_BASE | (i+1)` и, соответственно, очередь `200+i` НА
# ВОРКЕР — при 1024 воркерах это диапазон 200..1223. Скрипт снимает
# глубину/потери по всему диапазону 200..1300 (как в черновике брифа), а не
# только по 200 — иначе старая схема на этих колонках была бы нулём по
# построению, а не по факту.
#
# ── Трафик через метки — отдельная nft-цепочка, не procfs ────────────────
#
# Поле 3 (`queue_total`) — МГНОВЕННЫЙ бэклог очереди, а не счётчик: в этом же
# дереве `tests/e2e_infra.rs` (`queue_sequence`, doc-комментарий) прямо
# объясняет, что `nfqws2` выносит вердикт за микросекунды и почти никогда не
# оставляет пакет в очереди — проверка по `queue_total` была бы тестом на шум.
# `scan-packet-rate.sh` и `nfq-throughput-ab.sh` решают тот же вопрос
# отдельной наблюдательной nft-цепочкой со счётчиками (приоритет ПЕРЕД
# боевыми правилами, свой mark-фильтр, не зависит от перебиндов очереди) — тот
# же приём здесь, вместо "пиковой глубины" из procfs. `WORKER_MARK_BASE`
# (0x20000000) — тот же бит что и до #68 (`git show HEAD:src/config.rs`),
# так что приём одинаково валиден на обеих схемах.
#
# Потери (поля 6+7, `queue_dropped`+`user_dropped`) — оставлены из procfs:
# это НЕ мгновенный снимок, а фактические счётчики отброшенных пакетов,
# легитимный сигнал (см. ту же ловушку про обнуление при перебинде в
# nfq-throughput-ab.sh — берём максимум по выборкам, не дельту).
set -uo pipefail

DOMAIN="${1:-rutracker.org}"
TIMEOUT="${2:-70}"
PROFILES_PER_INSTANCE="${3:-1024}"
# Fix round 2: переопределяемо через окружение — `BIN=/oldsrc/target/debug/blockcheckw
# tests/repro/scan-rss-ab.sh`. Без этого A/B, ради которого написан весь
# скрипт, нечем было провести — второй билд было физически некуда указать.
BIN="${BIN:-/app/target/debug/blockcheckw}"
OBS_TABLE=bcw_rss_obs
EXPECTED_PROTOCOLS=3 # default -p http,tls12,tls13 — скрипт его не переопределяет
PID=0
ANY_FAILED=0

# ── C1: инструмент обязан отказывать, а не выдавать правдоподобное ───────
if [ ! -x "$BIN" ]; then
    echo "ERROR: $BIN отсутствует или не исполняем — измерять нечего" >&2
    exit 1
fi

# Умеет ли ЭТОТ бинарь --profiles-per-instance. На билде до задачи 8ч2
# такого флага нет вовсе (`git show HEAD:src/main.rs` — только --workers);
# передать его туда безусловно значило бы, что clap валит процесс за
# миллисекунды, а дальше пик PSS=0, запусков=0 — и это выглядело бы как
# "новая схема со всеми нулями", а не как отказ. Проверяем заранее и просто
# не передаём флаг там, где его нет.
HAS_PPI=0
if timeout 5 "$BIN" --help 2>&1 | grep -q -- '--profiles-per-instance'; then
    HAS_PPI=1
fi
echo "бинарь понимает --profiles-per-instance: $([ "$HAS_PPI" -eq 1 ] && echo да || echo нет)"

cleanup() {
    if [ "${PID:-0}" -ne 0 ]; then
        kill -INT "$PID" 2>/dev/null
        sleep 2
    fi
    pkill -9 -x blockcheckw 2>/dev/null
    pkill -9 -x nfqws2 2>/dev/null
    nft delete table inet blockcheckw 2>/dev/null
    nft delete table inet "$OBS_TABLE" 2>/dev/null
    true
}
trap cleanup EXIT

hard_reset() {
    pkill -9 -x blockcheckw 2>/dev/null
    pkill -9 -x nfqws2 2>/dev/null
    nft delete table inet blockcheckw 2>/dev/null
    nft delete table inet "$OBS_TABLE" 2>/dev/null
    sleep 1
    # L1: setup-router.sh готовит фикстуру, без которой обе схемы ведут себя
    # непредсказуемо — молчаливый провал здесь тоже дал бы правдоподобные
    # нули дальше по цепочке. Код возврата проверяем, а не давим в /dev/null.
    #
    # Путь НЕ привязан к $BIN и не переопределяется вместе с ним (Fix round
    # 2): это фикстура из ТЕКУЩЕГО чекаута репозитория (/app), общая для
    # обоих замеряемых билдов, а не часть конкретной сборки — старый билд из
    # /oldsrc вообще может не содержать своей копии tests/repro/, если собран
    # из старого коммита в отдельном дереве.
    if ! bash /app/tests/repro/setup-router.sh >/tmp/setup-router.out 2>&1; then
        echo "ERROR: setup-router.sh упал — стенд не готов, смотри /tmp/setup-router.out" >&2
        cat /tmp/setup-router.out >&2
        exit 1
    fi
}

# Наблюдательная цепочка для трафика через наши метки — см. врезку про H2
# выше. Пересоздаётся на каждом уровне, чтобы счётчики стартовали с нуля.
setup_obs_chain() {
    nft delete table inet "$OBS_TABLE" 2>/dev/null
    nft add table inet "$OBS_TABLE"
    nft add chain inet "$OBS_TABLE" po '{ type filter hook postrouting priority 101; }'
    nft add chain inet "$OBS_TABLE" pr '{ type filter hook prerouting priority -103; }'
    nft add rule inet "$OBS_TABLE" po mark and 0x20000000 != 0 counter
    nft add rule inet "$OBS_TABLE" pr ct mark and 0x20000000 != 0 counter
}
obs_pkt_count() {
    nft list table inet "$OBS_TABLE" 2>/dev/null | grep -oE 'packets [0-9]+' | awk '{s+=$2} END{print s+0}'
}

# Снять ANSI-раскраску (console::style) — защитная мера для полей, которые
# ею оборачиваются (не "completed:", он голый, но мало ли что ещё в логе).
strip_ansi() {
    sed -E $'s/\x1b\\[[0-9;]*m//g'
}

# ── Один проход опроса: PSS, уникальные PID, потери очереди ──────────────
#
# H3: раньше на каждый живой nfqws2 форкался свой awk (на 1024 воркерах
# старой схемы — ~1024 форка на тик). Сам замер начинал мешать тому, что
# меряет: заявленная частота 50 мс недостижима, ядро занято форками, а не
# работой nfqws2 — пики старой схемы недобираются, эффект #68 занижается.
# awk сам умеет несколько файлов в одном вызове: `/^Pss:/{s+=$2}` копит `s`
# по всем строкам ВСЕХ переданных файлов подряд (границы файлов ему тут не
# важны — нужна общая сумма, не по-файлово), `END{print s+0}` печатает её
# один раз. Одного вызова на весь список PID достаточно.
#
# `[ -r ... ]`-фильтр перед вызовом — не полная защита от гонки (процесс
# может умереть между проверкой и чтением), но у используемого здесь awk
# (mawk на Ubuntu, `awk --version` эквивалент) ЛЮБОЙ пропавший файл валит
# ВЕСЬ вызов (проверено: `awk ... a.txt missing.txt b.txt` не печатает
# ничего, exit=2, а не частичную сумму) — поэтому сужаем окно гонки, а не
# полагаемся на то, что awk сам пропустит недостающий файл.
PSS_PEAK=0
Q_DROP_PEAK=0
STARTS_PID_COUNT=0
sample_peaks() {
    local watch_pid=$1
    local -A seen_pids=()
    PSS_PEAK=0
    Q_DROP_PEAK=0
    while kill -0 "$watch_pid" 2>/dev/null; do
        local p paths sum line qdrop
        paths=()
        for p in $(pgrep -x nfqws2 2>/dev/null); do
            seen_pids[$p]=1
            [ -r "/proc/$p/smaps_rollup" ] && paths+=("/proc/$p/smaps_rollup")
        done
        if [ "${#paths[@]}" -gt 0 ]; then
            sum=$(awk '/^Pss:/{s+=$2} END{print s+0}' "${paths[@]}" 2>/dev/null)
        else
            sum=0
        fi
        [ -n "$sum" ] && [ "$sum" -gt "$PSS_PEAK" ] 2>/dev/null && PSS_PEAK=$sum

        # H1: диапазон 200..1300 — старая схема бинды очередь на воркер
        # (200+i), новая — всегда одну 200. Потери — максимум по выборкам,
        # не дельта: счётчики обнуляются при каждом перебинде очереди (та же
        # ловушка, что в nfq-throughput-ab.sh про id_sequence).
        line=$(awk '$1+0>=200 && $1+0<1300 {d+=$6+0; u+=$7+0} END{print d+u+0}' \
            /proc/net/netfilter/nfnetlink_queue 2>/dev/null)
        qdrop=${line:-0}
        [ "$qdrop" -gt "$Q_DROP_PEAK" ] 2>/dev/null && Q_DROP_PEAK=$qdrop

        sleep 0.05
    done
    STARTS_PID_COUNT=${#seen_pids[@]}
}

for workers in 8 64 1024; do
    if [ "$HAS_PPI" -eq 1 ] && [ "$workers" -gt "$PROFILES_PER_INSTANCE" ]; then
        printf 'workers=%-5s SKIP: workers > --profiles-per-instance=%s — validate_parallelism (config.rs) это отвергнет\n' \
            "$workers" "$PROFILES_PER_INSTANCE"
        continue
    fi

    hard_reset
    setup_obs_chain

    log="/tmp/scan-rss-w${workers}.log"
    : >"$log"

    cmd_args=(--auto -w "$workers")
    [ "$HAS_PPI" -eq 1 ] && cmd_args+=(--profiles-per-instance "$PROFILES_PER_INSTANCE")
    cmd_args+=(scan -d "$DOMAIN" --timeout "$TIMEOUT")

    RUST_LOG=blockcheckw=info "$BIN" "${cmd_args[@]}" >>"$log" 2>&1 &
    PID=$!

    sample_peaks "$PID"
    wait "$PID" 2>/dev/null
    rc=$?
    PID=0 # снят штатно — trap не должен слать SIGINT повторно чужому pid

    packets=$(obs_pkt_count)
    nft delete table inet "$OBS_TABLE" 2>/dev/null

    # ── C1: громкий отказ вместо правдоподобной строки с нулями ──────────
    if [ "$rc" -ne 0 ]; then
        echo "ERROR: workers=$workers: $BIN завершился кодом $rc — измерение недостоверно, смотри $log" >&2
        printf 'workers=%-5s ИЗМЕРЕНИЕ ПРОВАЛЕНО (exit=%s), см. %s\n' "$workers" "$rc" "$log"
        ANY_FAILED=1
        continue
    fi
    if [ "$PSS_PEAK" -eq 0 ]; then
        echo "ERROR: workers=$workers: пик PSS = 0 — ни один nfqws2 не был замечен опросом; измерению доверять нельзя" >&2
        printf 'workers=%-5s ИЗМЕРЕНИЕ ПРОВАЛЕНО (пик PSS=0), см. %s\n' "$workers" "$log"
        ANY_FAILED=1
        continue
    fi

    plain_log=$(strip_ansi <"$log")

    starts=$STARTS_PID_COUNT
    starts_log_marker=$(grep -c "nfqws2 instance started" <<<"$plain_log") # доп. сверка, только на новой схеме

